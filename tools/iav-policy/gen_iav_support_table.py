"""Generate the IAV ioctl support table of doc/IavVirtualization.md.

The table is built from two inputs, so it cannot drift from what the broker does:

  --dump    the output of build/iav-policy/iav_ioctl_dump (drivers/amba_virt/tools): the broker's own ioctl table with
            its allow-list applied (name, magic, ioctl number, profiles that may call it)
  --review  drivers/amba_virt/tools/iav_ioctl_review.tsv: a one-line description and the reason for each refusal

Modes: --write rewrites the section between the markers in --doc; --check fails (exit 1) when the document differs
from the generated section, when the review record and the broker's table name different ioctls, or when a refused
call has no reason or a served call has one.
"""
import argparse
import sys

BEGIN = '<!-- iav-support-table:begin (generated by tools/iav-policy/gen_iav_support_table.py; do not edit) -->'
END = '<!-- iav-support-table:end -->'

MAGIC_ENC, MAGIC_DEC, MAGIC_VIN, MAGIC_VOUT, MAGIC_IMAGE = 0, 1, 2, 3, 4

# Groups in the order of the driver's header: the encode ioctls are grouped by number range; decode, VIN device, VOUT
# and IMAGE ioctls have their own magic numbers.
GROUPS = [
    ('Driver and DSP (0x00 to 0x0F)', lambda m, n: m == MAGIC_ENC and n <= 0x0F),
    ('System (0x10 to 0x3F)', lambda m, n: m == MAGIC_ENC and 0x10 <= n <= 0x3F),
    ('Encode control (0x40 to 0x5F)', lambda m, n: m == MAGIC_ENC and 0x40 <= n <= 0x5F),
    ('VIN, IDSP and VCAP control (0x60 to 0x6F)', lambda m, n: m == MAGIC_ENC and 0x60 <= n <= 0x6F),
    ('AISP (0x70 to 0x7F)', lambda m, n: m == MAGIC_ENC and 0x70 <= n <= 0x7F),
    ('Miscellaneous (0xD0 and up)', lambda m, n: m == MAGIC_ENC and n >= 0xD0),
    ('Decode', lambda m, n: m == MAGIC_DEC),
    ('VIN device', lambda m, n: m == MAGIC_VIN),
    ('VOUT', lambda m, n: m == MAGIC_VOUT),
    ('IMAGE (3A statistics and image DSP debug)', lambda m, n: m == MAGIC_IMAGE),
]

CONSUMER, QUALIFICATION, PRIMARY = 1, 2, 4  # profile bits of iav_policy.h (1 << profile)


def read_dump(path):
    rows = {}
    with open(path) as f:
        for line in f:
            p = line.rstrip('\n').split('\t')
            if len(p) != 8:
                sys.exit('bad dump line: %r' % line)
            rows[p[0]] = dict(magic=int(p[1]), nr=int(p[2]), profiles=int(p[7], 16))
    return rows


def read_review(path):
    rows = {}
    with open(path) as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            p = line.rstrip('\n').split('\t')
            if len(p) != 3:
                sys.exit('bad review line (need name, description, reason): %r' % line)
            if p[0] in rows:
                sys.exit('duplicate review row: %s' % p[0])
            rows[p[0]] = dict(desc=p[1], reason=p[2])
    return rows


def support(profiles):
    if profiles & CONSUMER:
        return 'every guest'
    if profiles & PRIMARY:
        return 'primary guest only'
    if profiles & QUALIFICATION:
        return 'qualification runs only'
    return 'refused'


def check_inputs(dump, review):
    errors = []
    for n in sorted(set(dump) - set(review)):
        errors.append('%s is in the broker table but not in the review record' % n)
    for n in sorted(set(review) - set(dump)):
        errors.append('%s is in the review record but not in the broker table' % n)
    for n in sorted(set(dump) & set(review)):
        served = dump[n]['profiles'] != 0
        if not review[n]['desc'].strip():
            errors.append('%s has no description' % n)
        if served and review[n]['reason'].strip():
            errors.append('%s is served but the review record still gives a refusal reason' % n)
        if not served and not review[n]['reason'].strip():
            errors.append('%s is refused but has no reason' % n)
    return errors


def render(dump, review):
    out = []
    total = len(dump)
    counts = {'every guest': 0, 'primary guest only': 0, 'qualification runs only': 0, 'refused': 0}
    for r in dump.values():
        counts[support(r['profiles'])] += 1
    out.append(BEGIN)
    out.append('')
    out.append('All %d ioctls of the IAV driver on this platform: %d served to every guest, %d served to the primary guest '
               'only, %d refused (`EPERM`).' % (total, counts['every guest'], counts['primary guest only'], counts['refused']))
    if counts['qualification runs only']:
        sys.exit('ioctls served only in qualification mode are not expected in the table')
    out.append('')
    used = set()
    for title, pred in GROUPS:
        names = [n for n, r in dump.items() if pred(r['magic'], r['nr'])]
        if not names:
            continue
        used.update(names)
        names.sort(key=lambda n: (dump[n]['nr'], n))
        out.append('#### %s' % title)
        out.append('')
        out.append('| Ioctl | What it does | Supported | Reason when not served |')
        out.append('|---|---|---|---|')
        for n in names:
            e = review[n]
            out.append('| `%s` | %s | %s | %s |' % (n, e['desc'], support(dump[n]['profiles']), e['reason'] or ''))
        out.append('')
    missing = set(dump) - used
    if missing:
        sys.exit('ioctls outside every group: %s' % ', '.join(sorted(missing)))
    out.append(END)
    return '\n'.join(out)


def split_doc(text):
    a = text.find(BEGIN)
    b = text.find(END)
    if a < 0 or b < 0 or b < a:
        sys.exit('the markers of the support table are missing from the document')
    return text[:a], text[b + len(END):]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dump', required=True)
    ap.add_argument('--review', required=True)
    ap.add_argument('--doc', required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    a = ap.parse_args()
    dump = read_dump(a.dump)
    review = read_review(a.review)
    errors = check_inputs(dump, review)
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    table = render(dump, review)
    with open(a.doc) as f:
        text = f.read()
    head, tail = split_doc(text)
    new = head + table + tail
    if a.write:
        with open(a.doc, 'w') as f:
            f.write(new)
        print('wrote the support table of %d ioctls to %s' % (len(dump), a.doc))
        return 0
    if new != text:
        print('the support table in %s is out of date; run make -C drivers/amba_virt/tools iav-support-table' % a.doc,
              file=sys.stderr)
        return 1
    print('support table matches the broker allow-list and the review record (%d ioctls)' % len(dump))
    return 0


if __name__ == '__main__':
    sys.exit(main())
